import type { WeeklyMenuItemRequest } from './types/WeeklyMenuItemRequest'
import type { WeeklyMenuItemUpdateRequest } from './types/WeeklyMenuItemUpdateRequest'
import type { WeeklyMenuItemResponse } from './types/WeeklyMenuItemResponse'
import type { FastifyInstance, FastifyRequest } from 'fastify'
import type { WeeklyMenuItemController } from './WeeklyMenuItemController'
import type { ListItem, PaginatedResponse } from '../../../types/PaginatedResponse'

import { verifyDbSchema, verifyDbModel } from '../../../core/helper/db_utils'
import {toApiAttributes } from '../../../core/helper/api_helper';

import { toModelAttributes } from '../../../core/helper/api_helper';

function httpError(statusCode: number, message: string): Error & { statusCode: number } {
  return Object.assign(new Error(message), { statusCode })
}


export class WeeklyMenuItemService implements WeeklyMenuItemController {
      public async listWeeklyMenuItem(app: FastifyInstance, request?: FastifyRequest): Promise<PaginatedResponse<ListItem<WeeklyMenuItemResponse[]>>> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.cntn_weekly_menu_item.schema(schema!);
      const query = (request?.query ?? {}) as { page?: string | number; limit?: string | number }
      const parsePositiveInteger = (value: string | number | undefined, fallback: number) => {
        const parsed = Number(value)
        return Number.isInteger(parsed) && parsed > 0 ? parsed : fallback
      }
      const page = parsePositiveInteger(query.page, 1)
      const limit = Math.min(parsePositiveInteger(query.limit, 20), 100)
      const { count, rows } = await model.findAndCountAll({
        limit,
        offset: (page - 1) * limit,
      })
      return {
        data: rows.map((row) => toApiAttributes<ListItem<WeeklyMenuItemResponse[]>>(row.get({ plain: true }) as Record<string, unknown>)),
        pagination: {
          page,
          limit,
          total: count,
          totalPages: Math.ceil(count / limit),
        },
      }
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async createWeeklyMenuItem(app: FastifyInstance, input: WeeklyMenuItemRequest, request?: FastifyRequest): Promise<WeeklyMenuItemResponse> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.cntn_weekly_menu_item.schema(schema!);
      const row = await model.create(toModelAttributes(input) as any)
      return toApiAttributes<WeeklyMenuItemResponse>(row.get({ plain: true }) as Record<string, unknown>)
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async getWeeklyMenuItemById(app: FastifyInstance, request?: FastifyRequest): Promise<WeeklyMenuItemResponse> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.cntn_weekly_menu_item.schema(schema!);
      const { id } = (request?.params ?? {}) as { id?: string | number }
      if (id === undefined || id === '') throw httpError(400, 'id is required')
      const row = await model.findByPk(id)
      if (!row) {
        throw httpError(404, 'cntn_weekly_menu_item not found')
      }
      return toApiAttributes<WeeklyMenuItemResponse>(row.get({ plain: true }) as Record<string, unknown>)
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async updateWeeklyMenuItem(app: FastifyInstance, input: WeeklyMenuItemUpdateRequest, request?: FastifyRequest): Promise<WeeklyMenuItemResponse> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.cntn_weekly_menu_item.schema(schema!);
      const { id } = (request?.params ?? {}) as { id?: string | number }
      if (id === undefined || id === '') throw httpError(400, 'id is required')
      const row = await model.findByPk(id)
      if (!row) {
        throw httpError(404, 'cntn_weekly_menu_item not found')
      }
      await row.update(toModelAttributes(input) as any)
      return toApiAttributes<WeeklyMenuItemResponse>(row.get({ plain: true }) as Record<string, unknown>)
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async deleteWeeklyMenuItem(app: FastifyInstance, request?: FastifyRequest): Promise<void> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.cntn_weekly_menu_item.schema(schema!);
      const { id } = (request?.params ?? {}) as { id?: string | number }
      if (id === undefined || id === '') throw httpError(400, 'id is required')
      const deletedCount = await model.destroy({ where: { id } })
      if (deletedCount === 0) throw httpError(404, 'cntn_weekly_menu_item not found')
      return
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

}
