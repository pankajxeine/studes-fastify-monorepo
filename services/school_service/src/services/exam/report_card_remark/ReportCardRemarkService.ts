import type { ReportCardRemarkRequest } from './types/ReportCardRemarkRequest'
import type { ReportCardRemarkUpdateRequest } from './types/ReportCardRemarkUpdateRequest'
import type { ReportCardRemarkResponse } from './types/ReportCardRemarkResponse'
import type { FastifyInstance, FastifyRequest } from 'fastify'
import type { ReportCardRemarkController } from './ReportCardRemarkController'
import type { ListItem, PaginatedResponse } from '../../../types/PaginatedResponse'

import { verifyDbSchema, verifyDbModel } from '../../../core/helper/db_utils'
import {toApiAttributes } from '../../../core/helper/api_helper';

import { toModelAttributes } from '../../../core/helper/api_helper';

function httpError(statusCode: number, message: string): Error & { statusCode: number } {
  return Object.assign(new Error(message), { statusCode })
}


export class ReportCardRemarkService implements ReportCardRemarkController {
      public async listReportCardRemark(app: FastifyInstance, request?: FastifyRequest): Promise<PaginatedResponse<ListItem<ReportCardRemarkResponse[]>>> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.exam_report_card_remark.schema(schema!);
      const query = (request?.query ?? {}) as { page?: string | number; limit?: string | number }
      const parsePositiveInteger = (value: string | number | undefined, fallback: number) => {
        const parsed = Number(value)
        return Number.isInteger(parsed) && parsed > 0 ? parsed : fallback
      }
      const page = parsePositiveInteger(query.page, 1)
      const limit = Math.min(parsePositiveInteger(query.limit, 20), 100)
      const { count, rows } = await model.findAndCountAll({
        limit,
        offset: (page - 1) * limit,
      })
      return {
        data: rows.map((row) => toApiAttributes<ListItem<ReportCardRemarkResponse[]>>(row.get({ plain: true }) as Record<string, unknown>)),
        pagination: {
          page,
          limit,
          total: count,
          totalPages: Math.ceil(count / limit),
        },
      }
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async createReportCardRemark(app: FastifyInstance, input: ReportCardRemarkRequest, request?: FastifyRequest): Promise<ReportCardRemarkResponse> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.exam_report_card_remark.schema(schema!);
      const row = await model.create(toModelAttributes(input) as any)
      return toApiAttributes<ReportCardRemarkResponse>(row.get({ plain: true }) as Record<string, unknown>)
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async getReportCardRemarkById(app: FastifyInstance, request?: FastifyRequest): Promise<ReportCardRemarkResponse> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.exam_report_card_remark.schema(schema!);
      const { id } = (request?.params ?? {}) as { id?: string | number }
      if (id === undefined || id === '') throw httpError(400, 'id is required')
      const row = await model.findByPk(id)
      if (!row) {
        throw httpError(404, 'exam_report_card_remark not found')
      }
      return toApiAttributes<ReportCardRemarkResponse>(row.get({ plain: true }) as Record<string, unknown>)
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async updateReportCardRemark(app: FastifyInstance, input: ReportCardRemarkUpdateRequest, request?: FastifyRequest): Promise<ReportCardRemarkResponse> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.exam_report_card_remark.schema(schema!);
      const { id } = (request?.params ?? {}) as { id?: string | number }
      if (id === undefined || id === '') throw httpError(400, 'id is required')
      const row = await model.findByPk(id)
      if (!row) {
        throw httpError(404, 'exam_report_card_remark not found')
      }
      await row.update(toModelAttributes(input) as any)
      return toApiAttributes<ReportCardRemarkResponse>(row.get({ plain: true }) as Record<string, unknown>)
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

      public async deleteReportCardRemark(app: FastifyInstance, request?: FastifyRequest): Promise<void> {
    try {
      // tenant schema comes from request context
      const schema = request?.dbSchema;
      verifyDbSchema(schema)
      // bind model to tenant schema
      const models = app.models;
      verifyDbModel(models);
      const model = models.exam_report_card_remark.schema(schema!);
      const { id } = (request?.params ?? {}) as { id?: string | number }
      if (id === undefined || id === '') throw httpError(400, 'id is required')
      const deletedCount = await model.destroy({ where: { id } })
      if (deletedCount === 0) throw httpError(404, 'exam_report_card_remark not found')
      return
    } catch (err) {
      app.log.error(err);
      throw err;
    }
  }

}
